    FIRST_NAME,
    LAST_NAME,
    SALARY,
    NVL(COMMISSION_PCT, 0) AS DUZELDILMIS_KOMISSIYA -- NVL = REPLACEMENT
FROM
    HR.EMPLOYEES;

-- TASK 2
SELECT
    FIRST_NAME,
    LAST_NAME,
    SALARY
FROM
    HR.EMPLOYEES
