    UPPER(LAST_NAME) = 'KING';

-- TASK 3
SELECT
    FIRST_NAME,
    LAST_NAME,
    HIRE_DATE
FROM
    HR.EMPLOYEES
WHERE
    HIRE_DATE > TO_DATE('2006 - 1 - 1', 'YYYY-MM-DD');

-- TASK 4
SELECT
    FIRST_NAME,
    LAST_NAME,
    ROUND(MONTHS_BETWEEN(SYSDATE, HIRE_DATE)) AS STAJ_AY
FROM
    HR.EMPLOYEES;

-- TASK 5
SELECT
    FIRST_NAME,
    LAST_NAME,
    PHONE_NUMBER
FROM
    HR.EMPLOYEES
