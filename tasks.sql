    FIRST_NAME,
    LAST_NAME,
    HIRE_DATE
FROM
    HR.EMPLOYEES
WHERE
    EXTRACT(DAY FROM HIRE_DATE) > 15
    AND SALARY BETWEEN 5000 AND 12000;

