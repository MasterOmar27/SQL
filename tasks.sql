-- TASK 10
SELECT
    FIRST_NAME,
    HIRE_DATE
FROM
    HR.EMPLOYEES
WHERE
    HIRE_DATE BETWEEN TO_DATE('2005-01-01', 'YYYY-MM-DD') AND TO_DATE('2005-12-31', 'YYYY-MM-DD');

-- TASK 11
SELECT
    FIRST_NAME,
    SALARY                 AS MAAS,
    ROUND(0.8 * SALARY, 2) AS NET_MAAS
FROM
    HR.EMPLOYEES
WHERE
    DEPARTMENT_ID = 80;

-- TASK 12
SELECT
    FIRST_NAME,
    HIRE_DATE,
    JOB_ID
FROM
    HR.EMPLOYEES
WHERE
    HIRE_DATE BETWEEN TO_DATE('2003-01-01', 'YYYY-MM-DD') AND TO_DATE('2005-12-31', 'YYYY-MM-DD')
    AND JOB_ID != 'IT_PROG';

-- TASK 13
SELECT
    COUNT(*),
    ROUND(AVG(SALARY))
FROM
    HR.EMPLOYEES
WHERE
    COMMISSION_PCT IS NULL;

-- TASK 14
SELECT
    FIRST_NAME,
    SALARY
FROM
    HR.EMPLOYEES
WHERE
    MANAGER_ID IS NOT NULL
    AND DEPARTMENT_ID IS NOT NULL
ORDER BY
    SALARY DESC
FETCH FIRST 3 ROWS ONLY;

-- TASK 15
