-- TASK 1
SELECT
    E.FIRST_NAME AS ISCI_ADI,
    E.JOB_ID     AS ISCI_VEZIFESI,
    M.FIRST_NAME AS MENECER_ADI,
    M.JOB_ID     AS MENECER_VEZIFESI
FROM
    HR.EMPLOYEES E
    INNER JOIN HR.EMPLOYEES M ON E.MANAGER_ID = M.EMPLOYEE_ID;

-- TASK 2
SELECT
    E.FIRST_NAME,
    E.LAST_NAME,
    NVL(M.FIRST_NAME, 'YOXDUR') AS MENECER_ADI,
    NVL(M.LAST_NAME, 'YOXDUR')  AS MENECER_SOYADI
FROM
    HR.EMPLOYEES E
    LEFT JOIN HR.EMPLOYEES M ON E.MANAGER_ID = M.EMPLOYEE_ID;

-- TASK 3
SELECT DEPARTMENT_ID, DEPARTMENT_NAME, LOCATION_ID
FROM HR.DEPARTMENTS
WHERE LOCATION_ID IN (SELECT LOCATION_ID
                        FROM HR.LOCATIONS
                        WHERE COUNTRY_ID = 'UK');

-- TASK 4
SELECT
    E.FIRST_NAME, E.LAST_NAME, E.SALARY
FROM
    HR.EMPLOYEES E
INNER JOIN HR.EMPLOYEES M ON E.MANAGER_ID = M.EMPLOYEE_ID
WHERE M.FIRST_NAME = 'Neena' AND M.LAST_NAME = 'Kochhar'

-- TASK 5
SELECT
    E.FIRST_NAME,
    E.LAST_NAME,
    E.HIRE_DATE  AS ISCI_TARIX,
    M.FIRST_NAME AS MENECER_ADI,
    M.HIRE_DATE  AS MENECER_TARIX
FROM
    HR.EMPLOYEES E
    INNER JOIN HR.EMPLOYEES M ON E.MANAGER_ID = M.EMPLOYEE_ID
WHERE
    E.HIRE_DATE < M.HIRE_DATE;

-- TASK 6
SELECT
    E.FIRST_NAME,
    E.LAST_NAME,
    E.JOB_ID,
    M.FIRST_NAME AS MENECER_ADI,
    M.LAST_NAME AS MENECER_SOYADI
FROM HR.EMPLOYEES E
JOIN HR.EMPLOYEES M
    ON E.MANAGER_ID = M.EMPLOYEE_ID
WHERE E.JOB_ID = M.JOB_ID;

-- TASK 7
SELECT
    FIRST_NAME, LAST_NAME, JOB_ID, SALARY
FROM
    HR.EMPLOYEES 
WHERE JOB_ID IN (SELECT JOB_ID
                        FROM HR.JOBS
                        WHERE MAX_SALARY > 15000);

-- TASK 8
SELECT FIRST_NAME, SALARY
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IN (SELECT DEPARTMENT_ID
                            FROM HR.DEPARTMENTS
                            WHERE DEPARTMENT_NAME IN ('IT', 'Finance'));

-- TASK 9
SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME
FROM HR.EMPLOYEES
WHERE EMPLOYEE_ID NOT IN(SELECT DISTINCT MANAGER_ID
                            FROM HR.EMPLOYEES
                            WHERE MANAGER_ID IS NOT NULL);

-- TASK 10
SELECT 
    M.FIRST_NAME AS MENECER_ADI,
    M.LAST_NAME AS MENECER_SOYADI,
    MAX(E.SALARY) AS MAX_TABE_MAASI,
    MIN(E.SALARY) AS MIN_TABE_MAASI
FROM
    HR.EMPLOYEES E
JOIN
    HR.EMPLOYEES M ON E.MANAGER_ID = M.EMPLOYEE_ID
GROUP BY
    M.EMPLOYEE_ID,
    M.FIRST_NAME,
    M.LAST_NAME
HAVING AVG(E.SALARY) > 7000
ORDER BY MAX_TABE_MAASI DESC;

