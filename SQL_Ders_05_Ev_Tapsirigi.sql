-- TASK 1
SELECT 
    FIRST_NAME || ' ' || UPPER(LAST_NAME) AS TAM_AD,
    SUBSTR(FIRST_NAME, 1, 1) || '. ' || LAST_NAME AS QISA_AD,
    SUBSTR(LOWER(FIRST_NAME), 1, 1) || LOWER(LAST_NAME) || '@company.com' AS EMAIL
FROM
    HR.EMPLOYEES;

-- TASK 2
SELECT 
    FIRST_NAME,
    TO_CHAR(SALARY, '99,999') || ' AZN' AS MAAS,
    TO_CHAR(SALARY * 12, '999,999.00') || ' AZN' AS ILLIK_MAAS
FROM
    HR.EMPLOYEES
ORDER BY
    SALARY DESC; -- MAAS YAZSA IDIK, 
                 -- CHAR TIPINDE OLDUGUNA GORE 
                 -- ASCII YE GORE SIRALAYACAGDI

-- TASK 3
SELECT
    FIRST_NAME,
    TO_CHAR(HIRE_DATE, 'DD.MM.YYYY') AS ISE_GIRIS,
    EXTRACT(YEAR FROM HIRE_DATE) AS IL,
    TRIM(TO_CHAR(HIRE_DATE, 'Month')) AS AY_ADI,
    TRIM(TO_CHAR(HIRE_DATE, 'Day')) AS HEFTE_GUNU
FROM
    HR.EMPLOYEES
ORDER BY
    HIRE_DATE ASC;

-- TASK 4
SELECT
    FIRST_NAME || ' ' || LAST_NAME AS ISCI,
    TO_CHAR(HIRE_DATE, 'DD Month YYYY') AS ISE_GIRIS,
    TRUNC(MONTHS_BETWEEN(SYSDATE, HIRE_DATE) / 12) || ' il ' ||
    MOD(TRUNC(MONTHS_BETWEEN(SYSDATE, HIRE_DATE)), 12) || ' ay' AS STAJ
FROM
    HR.EMPLOYEES
ORDER BY
    MONTHS_BETWEEN(SYSDATE, HIRE_DATE) DESC;

-- TASK 5

-- a)
SELECT
    FIRST_NAME,
    HIRE_DATE,
    ADD_MONTHS(HIRE_DATE, 3) AS SINAQ_BITIR,
    LAST_DAY(HIRE_DATE) AS ILK_MAAS_GUNU,
    LAST_DAY(HIRE_DATE) - HIRE_DATE AS MAASA_QALAN_GUN
FROM
    HR.EMPLOYEES;

-- b)
SELECT
    ADD_MONTHS(TO_DATE('28.02.2025', 'DD.MM.YYYY'), 3)
FROM DUAL;

-- verilen tarix fevral ayinin son tarixi olduguna gore
-- ADD_MONTHS verdikde yene ayin son gununu qaytaracag

-- TASK 6
SELECT
    FIRST_NAME || ' ' || LAST_NAME || ', komissiya: ' ||
    NVL(TO_CHAR(COMMISSION_PCT, '0.00'), 'yoxdur') AS MELUMAT
FROM
    HR.EMPLOYEES
WHERE
    TO_CHAR(HIRE_DATE, 'MM') = '03';

-- CONCAT in icerisinde iki value olmalidi
-- TO_CHAR(...) yazilmasa 0.20 .2 kimi gorsenecek
-- MART ayini gostermek ucun 03 yazmag lazimdir

-- TASK 7
SELECT
    TO_CHAR(HIRE_DATE, 'MM') AS AY_NO,
    TO_CHAR(HIRE_DATE, 'Month') AS AY,
    COUNT(*) AS ISCI_SAYI
FROM
    HR.EMPLOYEES
GROUP BY
    TO_CHAR(HIRE_DATE, 'MM'),
    TO_CHAR(HIRE_DATE, 'Month')
ORDER BY AY_NO;
-- ORDER BY AY yazsaq, elifbe sirasi ile duzlenecekdi

-- TASK 8
SELECT
    EMPLOYEE_ID,
    LOWER(SUBSTR(FIRST_NAME, 1, 1))
    || LOWER(LAST_NAME)
    || LPAD(EMPLOYEE_ID, 4, '0')    AS LOGIN,
    REPLACE(PHONE_NUMBER, '.', '-') AS TELEFON
FROM
    HR.EMPLOYEES
WHERE
    LENGTH(LAST_NAME) >= 7
ORDER BY LOGIN;

-- TASK 9
SELECT
    EXTRACT(YEAR FROM HIRE_DATE) AS IL,
    COUNT(*) AS ISCI_SAYI,
    TO_CHAR(MIN(HIRE_DATE), 'DD.MM.YYYY') AS ILK_TARIX,
    TO_CHAR(MAX(HIRE_DATE), 'DD.MM.YYYY') AS SON_TARIX,
    TO_CHAR(AVG(SALARY), '999,999,990.00') AS ORTA_MAAS
FROM
    HR.EMPLOYEES
GROUP BY
    EXTRACT(YEAR FROM HIRE_DATE)
ORDER BY IL ASC;
-- en birinci MIN(HIRE_DATE), sonra TO_CHAR istifade etmeliyik

-- TASK 10

-- a)
SELECT
    FIRST_NAME,
    TO_CHAR(HIRE_DATE, 'Dy') || ',' || ' ' || TO_CHAR(HIRE_DATE, 'DD.MM.YYYY') AS ISE_GIRIS,
CASE
    WHEN TRIM(TO_CHAR(HIRE_DATE, 'DAY')) IN ('SATURDAY', 'SUNDAY')
    THEN 'Hefte sonu'
    ELSE 'Is gunu'
    END AS GUN_NOVU
FROM
    HR.EMPLOYEES;

-- SONDAKI BOSLUGLARA GORE ISLEMEYECEK

-- b)
SELECT
    TO_CHAR(HIRE_DATE, 'Day') AS GUN,
    COUNT(*) AS ISCI_SAYI
FROM
    HR.EMPLOYEES
GROUP BY
    TO_CHAR(HIRE_DATE, 'Day')
ORDER BY
    ISCI_SAYI DESC;
