-- TASK 1
SELECT
    FIRST_NAME,
    LAST_NAME,
    SALARY,
    CASE
        WHEN SALARY < 6000 THEN 'ASAGI'
        WHEN SALARY >= 6000 AND SALARY <= 12000 THEN 'ORTA'
        ELSE 'YUKSEK'
    END AS MAAS_SEVIYYESI
FROM
    HR.EMPLOYEES;

-- TASK 2
SELECT
    FIRST_NAME,
    JOB_ID,
    CASE
        WHEN JOB_ID = 'IT_PROG' THEN 'Proqramci'
        WHEN JOB_ID = 'SA_REP' THEN 'Satis numayendesi'
        WHEN JOB_ID = 'ST_CLERK' THEN 'Anbar iscisi'
        ELSE 'DIGER'
    END AS VEZIFE
FROM
    HR.EMPLOYEES;

-- TASK 3 
-- FIRST
SELECT
    FIRST_NAME,
    COMMISSION_PCT,
    CASE
        WHEN COMMISSION_PCT IS NULL THEN 'Komissiya yoxdur'
        ELSE 'Komissiya var'
    END AS KOMISSIYA_STATUSU
FROM
    HR.EMPLOYEES;

-- SECOND
SELECT
    FIRST_NAME,
    COMMISSION_PCT, 
    NVL2(COMMISSION_PCT, 'Komissiya var', 'Komissiya yoxdur') AS KOMISSIYA_STATUSU
FROM
    HR.EMPLOYEES;

-- TASK 4
SELECT
    CITY,
    COUNTRY_ID,
    CASE
        WHEN COUNTRY_ID IN ('US', 'CA', 'MX', 'BR') THEN 'Amerika'
        WHEN COUNTRY_ID IN ('UK', 'DE', 'IT', 'NL', 'CH') THEN 'Avropa'
        WHEN COUNTRY_ID IN ('JP', 'CN', 'IN', 'SG') THEN 'Asiya'
        ELSE 'Diger'
    END AS QITE
FROM
    HR.LOCATIONS;

-- TASK 5
SELECT
    FIRST_NAME,
    DEPARTMENT_ID,
    SALARY,
    CASE
        WHEN DEPARTMENT_ID = 80 THEN SALARY * 0.10
        WHEN DEPARTMENT_ID = 60 THEN SALARY * 0.15
        ELSE SALARY * 0.05
    END AS BONUS
FROM
    HR.EMPLOYEES
ORDER BY
    BONUS DESC;

-- TASK 6
SELECT
    FIRST_NAME,
    SALARY,
    CASE
        WHEN SALARY > 15000 THEN 'Yuksek' -- SERTLERIN ARDICILLIGI
        WHEN SALARY > 5000 THEN 'Orta'
        ELSE 'Asagi' -- THEN-den SONRA YAZILANLAR EYNI DATA TYPE DE OLMALIDI
    END AS "Seviyye" -- ALIAS CUT DIRNAG ILE YAZILMALIDI
FROM
    HR.EMPLOYEES;

-- TASK 7
SELECT
    FIRST_NAME,
    JOB_ID,
    MANAGER_ID,
    CASE
        WHEN MANAGER_ID IS NULL THEN 'Direktor'
        WHEN MANAGER_ID = 100 THEN 'Direktorun komandasi'
        WHEN JOB_ID LIKE '%MAN' OR JOB_ID LIKE '%MGR' THEN 'Menecer'
        ELSE 'Isci'
    END AS ROL
FROM
    HR.EMPLOYEES;

-- TASK 8
SELECT
    FIRST_NAME,
    SALARY,
    COMMISSION_PCT,
    SALARY * NVL(COMMISSION_PCT, 0) * 12 AS ILLIK_KOMISSIYA,
    SALARY * 12 + SALARY * NVL(COMMISSION_PCT, 0) * 12 AS ILLIK_GELIR
FROM
    HR.EMPLOYEES
ORDER BY
    ILLIK_GELIR DESC;

-- TASK 9
SELECT
    E.FIRST_NAME,
    J.JOB_TITLE,
    E.SALARY,
    J.MIN_SALARY,
    J.MAX_SALARY,
    CASE
        WHEN E.SALARY = J.MIN_SALARY THEN 'Minimumda'
        WHEN E.SALARY = J.MAX_SALARY THEN 'Maksimumda'
        WHEN E.SALARY < (J.MIN_SALARY + J.MAX_SALARY) / 2 THEN 'Asagi yarida'
        ELSE 'Yuxari yarida'
    END AS MOVQE
FROM
    HR.EMPLOYEES E
JOIN
    HR.JOBS J
ON
    E.JOB_ID = J.JOB_ID;

-- TASK 10
SELECT
    E.FIRST_NAME,
    E.LAST_NAME,
    NVL(D.DEPARTMENT_NAME, 'Sobesiz') AS SOBE,
    CASE
        WHEN D.DEPARTMENT_ID IS NULL THEN 'Melum deyil'
        WHEN L.CITY = 'Seattle' THEN 'Bas ofis'
        ELSE 'Filial'
    END AS OFIS
FROM
    HR.EMPLOYEES E
LEFT JOIN
    HR.DEPARTMENTS D
ON
    E.DEPARTMENT_ID = D.DEPARTMENT_ID
LEFT JOIN
    HR.LOCATIONS L
ON
    D.LOCATION_ID = L.LOCATION_ID;