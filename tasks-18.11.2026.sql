-- TASK 1
SELECT 
    FIRST_NAME,
    SUBSTR(UPPER(FIRST_NAME), 1, 2) || '-' || SUBSTR(LOWER(LAST_NAME), 1, 3) AS KOD_AD,
    REPLACE(PHONE_NUMBER, '.', '') AS TELEFON_TEMIZ,
    LENGTH(FIRST_NAME) + LENGTH(LAST_NAME) AS AD_UZUNLUQ
FROM
    HR.EMPLOYEES
ORDER BY AD_UZUNLUQ;

-- TASK 2
SELECT  
    FIRST_NAME,
    SALARY,
    NVL2(COMMISSION_PCT, COMMISSION_PCT * 100 || '%', 'TEYIN EDILMEYIB')  AS KOMISSIYA_FAIZ,
    TO_CHAR(SALARY * NVL(COMMISSION_PCT, 0), '$999,990.00') AS BONUS_MEBLEG
FROM
    HR.EMPLOYEES
WHERE
    SALARY > 5000
ORDER BY 
    SALARY DESC;

-- TASK 3
SELECT
    CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(FIRST_NAME, ' '), LAST_NAME), ' ['), JOB_ID), ' ]') AS ISCI_KARTI,
    -- CONCAT(FIRST_NAME, ' ', LAST_NAME, ' [', JOB_ID, ' ]')
    TO_CHAR(HIRE_DATE, 'Q') AS GIRIS_RUBU, -- Q = ILIN RUBU (1, 2, 3, 4)
    TO_CHAR(HIRE_DATE, 'DDD') AS ILIN_GUNU
FROM
    HR.EMPLOYEES;
-- 5 CONCAT LAZIMDIR

-- TASK 4
SELECT
    FIRST_NAME,
    TO_CHAR(HIRE_DATE, 'DD-Mon-YYYY') AS ISE_GIRIS,
    TO_CHAR(NEXT_DAY(HIRE_DATE, 'MONDAY'), 'DD.MM.YYYY') AS TELIM_TARIXI,
    NEXT_DAY(HIRE_DATE, 'MONDAY') - HIRE_DATE AS GOZLEME_GUNU
FROM
    HR.EMPLOYEES
WHERE
    JOB_ID IN ('IT_PROG', 'SA_REP');

-- TASK 5
-- a)
SELECT
    TRUNC(MONTHS_BETWEEN(SYSDATE, TO_DATE('15.10.1998', 'DD.MM.YYYY')) / 12) AS TAM_YAS
FROM DUAL;
-- AYLARDA GUN SAYININ EYNI OLMADIGI UCUN /365 DOGRU DEYIL

-- b)
SELECT
    TO_CHAR(ADD_MONTHS(TO_DATE('31.01.2025', 'DD.MM.YYYY'), 1), 'DD.MM.YYYY') AS Yeni_Tarix
FROM DUAL;

-- TASK 6


-- TASK 7
SELECT
    DEPARTMENT_ID,
    COUNT(*) AS ISCI_SAYI,
    TO_CHAR(MIN(HIRE_DATE), 'DD.MM.YYYY') AS ILK_ISCI_TARIX,
    TO_CHAR(MAX(HIRE_DATE), 'DD.MM.YYYY') AS SON_ISCI_TARIX,
    TRUNC(MAX(HIRE_DATE) - MIN(HIRE_DATE)) AS GUN_FERQI
FROM
    HR.EMPLOYEES
WHERE
    DEPARTMENT_ID IS NOT NULL
GROUP BY DEPARTMENT_ID
ORDER BY DEPARTMENT_ID ASC;

-- TASK 8
SELECT
    'EMP' || '-' || LPAD(EMPLOYEE_ID, 5, '0') || '-' || SUBSTR(FIRST_NAME, 1, 1) || SUBSTR(LAST_NAME, 1, 1) AS KART_NO,
    LAST_NAME,
    LENGTH(EMAIL) AS EMAIL_UZUNLUQ,
    INSTR(LAST_NAME, 'a') AS ILK_HERF_YERI
FROM
    HR.EMPLOYEES
WHERE
    INSTR(LAST_NAME, 'a') > 0;

-- TASK 9
SELECT
    TO_CHAR(HIRE_DATE, 'Q') AS RUB,
    TO_CHAR(HIRE_DATE, 'MM') AS AY_NO,
    TO_CHAR(HIRE_DATE, 'fmMonth') AS AY_ADI,
    COUNT(*) AS ISCI_SAYI,
    TO_CHAR(SUM(SALARY), '$999,999,999') AS CEMI_MAAS
FROM
    HR.EMPLOYEES
GROUP BY
    TO_CHAR(HIRE_DATE, 'Q'),
    TO_CHAR(HIRE_DATE, 'MM'),
    TO_CHAR(HIRE_DATE, 'fmMonth')
ORDER BY
    RUB ASC,
    AY_NO ASC;

-- TASK 10
-- a)
SELECT
    FIRST_NAME,
    HIRE_DATE,
    TO_CHAR(TRUNC(HIRE_DATE, 'YYYY'), 'DD.MM.YYYY') AS ILIN_ILK_GUNU,
    TO_CHAR(TRUNC(ADD_MONTHS(HIRE_DATE, 12), 'YYYY') - 1, 'DD.MM.YYYY') AS ILIN_SON_GUNU,
    TRUNC(ADD_MONTHS(HIRE_DATE, 12), 'YYYY') - 1 - TRUNC(HIRE_DATE) AS ILE_QALAN_GUN    
FROM 
    HR.EMPLOYEES;

