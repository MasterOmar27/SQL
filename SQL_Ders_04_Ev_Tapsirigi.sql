-- TASK 1
SELECT
    E.FIRST_NAME,
    E.LAST_NAME,
    M.FIRST_NAME AS MENECER_ADI,
    M.LAST_NAME AS MENECER_SOYADI
FROM
    HR.EMPLOYEES E
JOIN    
    HR.EMPLOYEES M
ON E.MANAGER_ID = M.EMPLOYEE_ID;

-- TASK 2
SELECT
    E.FIRST_NAME,
    E.LAST_NAME,
    M.FIRST_NAME AS MENECER_ADI,
    M.LAST_NAME AS MENECER_SOYADI
FROM
    HR.EMPLOYEES E
LEFT JOIN    
    HR.EMPLOYEES M
ON E.MANAGER_ID = M.EMPLOYEE_ID;
-- SETIR FERGI OLMADI, SADECE LEFT JOIN YAZDIG KI, ESAS TABLE DA ITKI BAS VERMESIN

-- TASK 3
SELECT
    FIRST_NAME,
    LAST_NAME,
    DEPARTMENT_ID
FROM
    HR.EMPLOYEES
WHERE
    DEPARTMENT_ID IN (SELECT DEPARTMENT_ID
                      FROM HR.DEPARTMENTS
                      WHERE LOCATION_ID = 1700);

-- TASK 4
SELECT
    E.FIRST_NAME,
    E.LAST_NAME,
    M.FIRST_NAME AS MENECER_ADI,
    M.LAST_NAME AS MENECER_SOYADI
FROM
    HR.EMPLOYEES E
JOIN    
    HR.EMPLOYEES M
ON E.MANAGER_ID = M.EMPLOYEE_ID
WHERE
    M.FIRST_NAME = 'Steven'
AND
    M.LAST_NAME = 'King'

-- TASK 5
SELECT
    E.FIRST_NAME,
    E.LAST_NAME,
    E.SALARY,
    M.FIRST_NAME AS MENECER_ADI,
    M.SALARY AS MENECER_MAASI
FROM
    HR.EMPLOYEES E
JOIN    
    HR.EMPLOYEES M
ON E.MANAGER_ID = M.EMPLOYEE_ID
WHERE
    E.SALARY > M.SALARY;

-- TASK 6
SELECT
    E.FIRST_NAME,
    E.LAST_NAME,
    E.DEPARTMENT_ID,
    M.FIRST_NAME AS MENECER_ADI,
    M.DEPARTMENT_ID AS MENECER_SOBESI
FROM
    HR.EMPLOYEES E
JOIN    
    HR.EMPLOYEES M
ON E.MANAGER_ID = M.EMPLOYEE_ID
WHERE
    E.DEPARTMENT_ID != M.DEPARTMENT_ID;

-- TASK 7
SELECT
    FIRST_NAME,
    LAST_NAME,
    JOB_ID,
    SALARY
FROM
    HR.EMPLOYEES
WHERE
    JOB_ID IN (SELECT JOB_ID
                      FROM HR.JOBS
                      WHERE MIN_SALARY >= 10000);

-- TASK 8
SELECT FIRST_NAME, LAST_NAME
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IN (SELECT DEPARTMENT_ID -- BERABER EVEZINE IN OLMALIDI, TEKCE DEPARTMENT_ID YAZILMALIDI
                       FROM HR.DEPARTMENTS
                       WHERE DEPARTMENT_NAME IN ('Sales', 'IT')); -- Sales SEHV YAZILIB

-- TASK 9
-- a) IN ilə subquery
SELECT
    EMPLOYEE_ID,
    FIRST_NAME,
    LAST_NAME
FROM
    HR.EMPLOYEES
WHERE
    EMPLOYEE_ID IN (SELECT MANAGER_ID
                    FROM HR.EMPLOYEES
                    WHERE MANAGER_ID IS NOT NULL);

-- b) SELF JOIN
SELECT DISTINCT -- HER BIRINI BIR DEFE CIXISA VERMEK UCUN
    M.EMPLOYEE_ID,
    M.FIRST_NAME,
    M.LAST_NAME
FROM
    HR.EMPLOYEES M
JOIN HR.EMPLOYEES E
    ON M.EMPLOYEE_ID = E.MANAGER_ID;

-- TASK 10
SELECT
    M.FIRST_NAME AS MENECER_ADI,
    M.LAST_NAME AS MENECER_SOYADI,
    COUNT(E.EMPLOYEE_ID) AS TABE_SAYI,
    ROUND(AVG(E.SALARY)) AS TABELERIN_ORTA_MAASI
FROM
    HR.EMPLOYEES M
JOIN HR.EMPLOYEES E
    ON M.EMPLOYEE_ID = E.MANAGER_ID
GROUP BY
    M.EMPLOYEE_ID,
    M.FIRST_NAME,
    M.LAST_NAME
HAVING
    COUNT(E.EMPLOYEE_ID) > 5
ORDER BY
    TABE_SAYI DESC;