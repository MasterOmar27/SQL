-- TASK 1
SELECT
    MANAGER_ID,
    COUNT(*) AS ISCI_SAYI
FROM
    HR.EMPLOYEES
GROUP BY
    MANAGER_ID
ORDER BY
    ISCI_SAYI DESC;

-- TASK 2
SELECT
    COUNTRY_ID,
    COUNT(*) AS OFIS_SAYI
FROM
    HR.LOCATIONS
GROUP BY
    COUNTRY_ID
ORDER BY
    OFIS_SAYI DESC;

-- TASK 3
SELECT
    E.FIRST_NAME,
    E.LAST_NAME,
    J.JOB_TITLE
FROM
    HR.EMPLOYEES E
JOIN
    HR.JOBS J
ON
    E.JOB_ID = J.JOB_ID;

-- TASK 4
SELECT
    DEPARTMENT_ID,
    ROUND(AVG(SALARY), 2) AS ORTA_MAAS
FROM
    HR.EMPLOYEES
GROUP BY
    DEPARTMENT_ID
HAVING
    AVG(SALARY) > 8000;

-- TASK 5
SELECT
    DEPARTMENT_ID,
    COUNT(SALARY) AS ISCI_SAYI
FROM
    HR.EMPLOYEES
WHERE
    SALARY >= 3000
GROUP BY
    DEPARTMENT_ID
HAVING
    COUNT(SALARY) > 3;

-- TASK 6
SELECT
    J.JOB_TITLE,
    COUNT(FIRST_NAME) AS ISCI_SAYI
FROM
    HR.EMPLOYEES E
JOIN
    HR.JOBS J
ON
    E.JOB_ID = J.JOB_ID
GROUP BY
    J.JOB_TITLE
ORDER BY
    ISCI_SAYI DESC;

-- TASK 7
SELECT
    L.CITY,
    L.COUNTRY_ID
FROM
    HR.LOCATIONS L
LEFT JOIN
    HR.DEPARTMENTS D
ON
    L.LOCATION_ID = D.LOCATION_ID
WHERE
    D.DEPARTMENT_ID IS NULL;

-- TASK 8
SELECT
    J.JOB_TITLE,
    AVG(E.SALARY) AS ORTA_MAAS -- CIXISA LAST_NAME VERMEYE EHTIYAC YOXDU 
                               -- EHTIYAC OLSA ONU DA GROUP BY ILE VERMEK LAZIMDI
FROM
    HR.EMPLOYEES E
JOIN
    HR.JOBS J
ON
    E.JOB_ID = J.JOB_ID -- JOB_ID-nin GABAGINDAKI 'J' ALIAS-i GOSTERILMEMISDI
GROUP BY
    J.JOB_TITLE
HAVING
    AVG(E.SALARY) > 10000; -- WHERE ILE AGREGATE FUNC-LAR YAZMAG OLMUR

-- TASK 9
SELECT
    L.CITY,
    COUNT(FIRST_NAME) AS ISCI_SAYI,
    ROUND(AVG(E.SALARY)) AS ORTA_MAAS
FROM
    HR.EMPLOYEES E
JOIN
    HR.DEPARTMENTS D
ON
    E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN
    HR.LOCATIONS L
ON
    D.LOCATION_ID = L.LOCATION_ID
GROUP BY
    L.CITY
HAVING
    COUNT(FIRST_NAME) > 5
ORDER BY
    ISCI_SAYI DESC;

-- TASK 10
SELECT
    D.DEPARTMENT_NAME,
    COUNT(E.EMPLOYEE_ID) AS ISCI_SAYI
FROM
    HR.DEPARTMENTS D
LEFT JOIN
    HR.EMPLOYEES E
ON
    D.DEPARTMENT_ID = E.DEPARTMENT_ID
GROUP BY
    D.DEPARTMENT_ID,
    D.DEPARTMENT_NAME
ORDER BY
    ISCI_SAYI DESC,
    D.DEPARTMENT_NAME ASC;